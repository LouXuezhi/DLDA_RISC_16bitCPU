// fib -- 20 次迭代的斐波那契，无访存。每次迭代一个必中的分支，
// 所以这个核测的是「跳转杀掉一条指令」的代价 —— 分支预测器的基线。
//   R0 = 0 常量兼基址   R2 = a   R1 = b   R3 = 计数
//   一次迭代走两步：a += b ; b += a，因此不需要临时寄存器。
//   20 次之后 a = F41, b = F42，取模 2^16。
        LI   R0, #0
        LI   R2, #1          ; a = F1
        LI   R1, #1          ; b = F2
        LI   R3, #20         ; 迭代次数
loop:   ADD  R2, R2, R1      ; a += b
        ADD  R1, R1, R2      ; b += a
        ADDI R3, R3, #-1
        BNE  R3, R0, loop
        ST   R1, -1(R0)      ; M[0xFF] = b -> LED
        HALT R3
